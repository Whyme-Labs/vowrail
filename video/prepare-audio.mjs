import {execFileSync} from 'node:child_process';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const here=fileURLToPath(new URL('.',import.meta.url));
const input=resolve(process.argv[2]??'');
if(!process.argv[2])throw Error('Supply the private uploaded clip path.');
const work=join(here,'renders/audio-preparation');mkdirSync(work,{recursive:true});
const probe=JSON.parse(execFileSync('ffprobe',['-v','error','-select_streams','a:0','-show_entries','stream=duration,sample_rate,channels','-of','json',input],{encoding:'utf8',timeout:15000}));
const seconds=Number(probe.streams?.[0]?.duration);
if(!Number.isFinite(seconds)||seconds<=1)throw Error('The supplied clip needs an audio track longer than one second.');
const trimArg=process.argv.slice(3).find(a=>a.startsWith('--trim-end-seconds='));
const trimEndSeconds=trimArg?Number(trimArg.split('=')[1]):0;
if(!Number.isFinite(trimEndSeconds)||trimEndSeconds<0||trimEndSeconds>=seconds-1)throw Error('End trim must leave more than one second of source audio.');
const trimmedSeconds=seconds-trimEndSeconds;
const normalized=join(work,'normalized.wav');
const trimFilter=trimEndSeconds?'atrim=duration='+trimmedSeconds+',asetpts=PTS-STARTPTS,':'';
execFileSync('ffmpeg',['-v','error','-nostdin','-y','-threads','1','-i',input,'-map','0:a:0','-vn','-af',trimFilter+'loudnorm=I=-18:TP=-1.5:LRA=9','-ar','48000','-ac','2','-map_metadata','-1',normalized],{timeout:60000});
const normalizedProbe=JSON.parse(execFileSync('ffprobe',['-v','error','-show_entries','format=duration','-of','json',normalized],{encoding:'utf8',timeout:15000}));
const clipSeconds=Number(normalizedProbe.format.duration);const crossfade=.5;
const loops=Math.ceil((90-crossfade)/(clipSeconds-crossfade));
if(loops<1||loops>100)throw Error('Invalid audio loop count.');
const labels=Array.from({length:loops},(_,i)=>'a'+i);
let filter=loops===1?'[0:a]anull[bed]':'[0:a]asplit='+loops+labels.map(l=>'['+l+']').join('');
let prior=labels[0];
for(let i=1;i<loops;i++){const next=i===loops-1?'bed':'join'+i;filter+=';['+prior+']['+labels[i]+']acrossfade=d='+crossfade+':c1=tri:c2=tri['+next+']';prior=next;}
filter+=';[bed]atrim=duration=90,afade=t=in:d=0.35,afade=t=out:st=88.8:d=1.2[out]';
const output=join(here,'public/supplied-audio.m4a');
execFileSync('ffmpeg',['-v','error','-nostdin','-y','-threads','1','-i',normalized,'-filter_complex_threads','1','-filter_complex',filter,'-map','[out]','-c:a','aac','-b:a','192k','-threads','1','-map_metadata','-1',output],{timeout:60000});
const digest=value=>createHash('sha256').update(value).digest('hex');
const bytes=readFileSync(output);const source=readFileSync(input);
const entry={file:'supplied-audio.m4a',provenance:'User-uploaded audio only; '+trimEndSeconds+'s removed from source end before normalization/looping; 0.5s joins and final fade; uploaded video excluded',bytes:bytes.length,sha256:digest(bytes)};
const manifestPath=join(here,'public/asset-manifest.json');const manifest=JSON.parse(readFileSync(manifestPath));
manifest.files=manifest.files.filter(f=>f.file!==entry.file).concat(entry);
manifest.audio={sourceSha256:digest(source),sourceBytes:source.length,sourceSeconds:seconds,trimEndSeconds,trimmedSourceSeconds:clipSeconds,seconds:90,loops,crossfadeSeconds:crossfade,fadeOutSeconds:1.2};
writeFileSync(manifestPath,JSON.stringify(manifest,null,2)+'\n');
writeFileSync(join(work,'audio-report.json'),JSON.stringify({result:'PASS',...manifest.audio,output,sha256:entry.sha256,bytes:entry.bytes,uploadedVideoIncluded:false},null,2)+'\n');
console.log(JSON.stringify({result:'PASS',sourceSeconds:seconds,trimEndSeconds,trimmedSourceSeconds:clipSeconds,seconds:90,loops,sha256:entry.sha256,uploadedVideoIncluded:false}));
